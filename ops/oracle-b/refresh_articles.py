def plain(value):
    return re.sub(r"<[^>]*>", "", value).strip()


def fetch_photo(filename):
    import httpx
    from urllib.parse import quote
    url = "https://commons.wikimedia.org/wiki/Special:Redirect/file/" + quote(filename, safe="")
    response = httpx.get(url, follow_redirects=True, timeout=45,
                         headers={"User-Agent": "BinzhouIndex/1.0 (licensed-image reuse with attribution)"})
    response.raise_for_status()
    mime = response.headers.get("content-type", "image/jpeg").split(";")[0]
    if not mime.startswith("image/") or len(response.content) < 10000:
        raise RuntimeError("Commons returned an invalid image: " + filename)
    return response.content, mime


